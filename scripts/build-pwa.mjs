// Generates public/manifest.webmanifest and public/sw.js at build time.
// - Manifest colors come from the theme (--meta-theme-color, --bg).
// - The service worker precaches the app shell, versioned by a hash of the shell files, so a new deploy
//   is a new worker ("Update ready" in the app). It never caches /api/ (the calendar relay) or anything
//   that looks like a calendar link: calendar data lives only in the browser's localStorage.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tokens } from './theme-tokens.mjs';
const root = new URL('../public/', import.meta.url);
const t = tokens();
const manifest = {
  name: 'Schoology Board', short_name: 'Sch. Board',
  description: 'Tonight\u2019s homework plan from your Schoology calendar. Works offline.',
  id: '/', start_url: '/?view=now&source=app', scope: '/', display: 'standalone', orientation: 'any',
  theme_color: t['--meta-theme-color'], background_color: t['--bg'],
  icons: [
    { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: '/icons/maskable-192.png', sizes: '192x192', type: 'image/png', purpose: 'maskable' },
    { src: '/icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
  ]
};
writeFileSync(new URL('manifest.webmanifest', root), JSON.stringify(manifest, null, 2) + '\n');
// Every theme's CSS is tiny, so all seven are in the shell; only the default theme's fonts are. Other fonts are kept after first use.
const THEMES = ['sticker', 'arcade', 'notebook', 'varsity', 'riso', 'cafe', 'minimal', 'nocturne'];
const SHELL = ['/', '/board/theme/default.css', '/board/tonight.css', '/board/board.css', ...THEMES.map((n) => `/board/theme/${n}.css`),
  '/board/theme/fonts/Fredoka.woff2', '/board/theme/fonts/Nunito.woff2', '/board/vendor/qrcode.js', '/board/ics.js', '/board/cas.js', '/board/plan.js', '/board/wedge.js', '/board/board.js',
  '/favicon.svg', '/manifest.webmanifest', '/icons/icon-192.png', '/icons/apple-touch-icon.png'];
const h = createHash('sha256');
for (const f of SHELL) { const p = new URL('.' + (f === '/' ? '/index.html' : f), root); if (existsSync(p)) h.update(readFileSync(p)); }
const version = h.digest('hex').slice(0, 12);
const sw = `/* Schoology Board service worker (generated by scripts/build-pwa.mjs). Version ${version}. */
const CACHE = 'sb-shell-${version}', RUNTIME = 'sb-runtime-v1';
const SHELL = ${JSON.stringify(SHELL)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL.map((u) => new Request(u, { cache: 'reload' }))))); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('sb-shell-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('message', (e) => { if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting(); });
// Never cached: the relay, other origins, non-GET requests, and anything that looks like a calendar link.
const PRIVATE = /\\/api\\/|webcal|ical|calendar\\/feed|\\.ics(\\?|$)/i;
self.addEventListener('fetch', (e) => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin || PRIVATE.test(url.pathname + url.search)) return;
  if (req.mode === 'navigate') {
    if (url.pathname !== '/' && url.pathname !== '/index.html') return;
    e.respondWith(caches.match('/', { cacheName: CACHE }).then((r) => r || fetch(req)));
    return;
  }
  if (SHELL.includes(url.pathname)) { e.respondWith(caches.match(url.pathname, { cacheName: CACHE }).then((r) => r || fetch(req))); return; }
  // Big optional pieces (the PDF reader, the sample board's picture) are kept after first use.
  if (/^\\/board\\/(vendor|preview|theme\\/fonts)/.test(url.pathname) || url.pathname.startsWith('/icons/')) {
    e.respondWith(caches.open(RUNTIME).then((c) => c.match(req).then((hit) => hit || fetch(req).then((res) => { if (res.ok) c.put(req, res.clone()); return res; }))));
  }
});
`;
writeFileSync(new URL('sw.js', root), sw);
console.log('pwa: manifest + sw.js', version);
